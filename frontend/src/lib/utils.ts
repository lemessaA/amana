export function cn(...classes: (string | boolean | undefined | null)[]): string {
  return classes.filter(Boolean).join(" ");
}

export function formatDate(date: string | Date): string {
  const d = typeof date === "string" ? new Date(date) : date;
  return d.toLocaleDateString("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
}

export function formatDateTime(date: string | Date): string {
  const d = typeof date === "string" ? new Date(date) : date;
  return d.toLocaleDateString("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

export function formatRelativeTime(date: string | Date): string {
  const d = typeof date === "string" ? new Date(date) : date;
  const now = new Date();
  const diff = now.getTime() - d.getTime();
  const seconds = Math.floor(diff / 1000);
  const minutes = Math.floor(seconds / 60);
  const hours = Math.floor(minutes / 60);
  const days = Math.floor(hours / 24);

  if (days > 0) return `${days}d ago`;
  if (hours > 0) return `${hours}h ago`;
  if (minutes > 0) return `${minutes}m ago`;
  return "just now";
}

export function getStatusColor(
  status: string
): "green" | "amber" | "red" | "gray" | "blue" {
  const lower = status.toLowerCase();
  if (lower.includes("approved") || lower.includes("completed") || lower.includes("active"))
    return "green";
  if (lower.includes("pending") || lower.includes("investigating") || lower.includes("triage"))
    return "amber";
  if (lower.includes("rejected") || lower.includes("restricted"))
    return "red";
  if (lower.includes("closed") || lower.includes("cancelled") || lower.includes("expired"))
    return "gray";
  return "blue";
}
